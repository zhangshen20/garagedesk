"""Tax invoice and receipt PDFs (Australian format: ABN, GST shown separately)."""

from __future__ import annotations

import os
from datetime import datetime

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.pdfgen import canvas
from sqlmodel import Session, select

from .config import get_settings
from .models import Customer, Invoice, Job, JobLine, Payment, Vehicle


def _money(cents: int) -> str:
    return f"${cents / 100:,.2f}"


def _files_dir() -> str:
    d = os.path.join(get_settings().files_dir, "invoices")
    os.makedirs(d, exist_ok=True)
    return d


def _header(c: canvas.Canvas, title: str, number: str, issued: datetime) -> float:
    s = get_settings()
    w, h = A4
    c.setFillColor(colors.HexColor("#0f172a"))
    c.rect(0, h - 38 * mm, w, 38 * mm, fill=1, stroke=0)
    c.setFillColor(colors.white)
    c.setFont("Helvetica-Bold", 20)
    c.drawString(20 * mm, h - 16 * mm, s.shop_name)
    c.setFont("Helvetica", 9)
    c.drawString(20 * mm, h - 22 * mm, f"{s.shop_trading_name}  ·  ABN {s.shop_abn}")
    c.drawString(20 * mm, h - 27 * mm, f"{s.shop_address}  ·  {s.shop_phone}  ·  {s.shop_email}")
    c.setFont("Helvetica-Bold", 16)
    c.drawRightString(w - 20 * mm, h - 16 * mm, title)
    c.setFont("Helvetica", 9)
    c.drawRightString(w - 20 * mm, h - 22 * mm, number)
    c.drawRightString(w - 20 * mm, h - 27 * mm, issued.strftime("%d %b %Y"))
    c.setFillColor(colors.black)
    return h - 50 * mm


def _party(c: canvas.Canvas, y: float, inv: Invoice, s: Session) -> float:
    cust = s.get(Customer, inv.customer_id)
    job = s.get(Job, inv.job_id)
    veh = s.get(Vehicle, job.vehicle_id) if job and job.vehicle_id else None
    c.setFont("Helvetica-Bold", 10)
    c.drawString(20 * mm, y, "Bill to")
    c.setFont("Helvetica", 10)
    c.drawString(20 * mm, y - 5 * mm, cust.name if cust else "")
    c.drawString(20 * mm, y - 10 * mm, cust.phone if cust else "")
    if cust and cust.email:
        c.drawString(20 * mm, y - 15 * mm, cust.email)
    c.setFont("Helvetica-Bold", 10)
    c.drawString(110 * mm, y, "Vehicle")
    c.setFont("Helvetica", 10)
    if veh:
        c.drawString(110 * mm, y - 5 * mm, f"{veh.year or ''} {veh.make} {veh.model}".strip())
        c.drawString(110 * mm, y - 10 * mm, f"Rego {veh.rego}")
        if veh.odometer_km:
            c.drawString(110 * mm, y - 15 * mm, f"Odometer {veh.odometer_km:,} km")
    c.drawString(110 * mm, y - 20 * mm, f"Job: {job.title if job else ''}")
    return y - 30 * mm


def _lines(c: canvas.Canvas, y: float, inv: Invoice, s: Session) -> float:
    w, _ = A4
    lines = s.exec(select(JobLine).where(JobLine.job_id == inv.job_id)).all()
    c.setFont("Helvetica-Bold", 9)
    c.setFillColor(colors.HexColor("#f1f5f9"))
    c.rect(20 * mm, y - 2 * mm, w - 40 * mm, 7 * mm, fill=1, stroke=0)
    c.setFillColor(colors.black)
    c.drawString(22 * mm, y, "Description")
    c.drawRightString(135 * mm, y, "Qty")
    c.drawRightString(160 * mm, y, "Unit (ex GST)")
    c.drawRightString(w - 22 * mm, y, "Amount")
    y -= 8 * mm
    c.setFont("Helvetica", 9)
    for l in lines:
        c.drawString(22 * mm, y, f"[{l.kind.value}] {l.description}"[:70])
        c.drawRightString(135 * mm, y, f"{l.qty:g}")
        c.drawRightString(160 * mm, y, _money(l.unit_cents))
        c.drawRightString(w - 22 * mm, y, _money(int(round(l.qty * l.unit_cents))))
        y -= 6 * mm
    y -= 4 * mm
    c.line(110 * mm, y + 2 * mm, w - 20 * mm, y + 2 * mm)
    for label, val, bold in (("Subtotal (ex GST)", inv.subtotal_cents, False), ("GST 10%", inv.gst_cents, False), ("TOTAL (inc GST)", inv.total_cents, True)):
        c.setFont("Helvetica-Bold" if bold else "Helvetica", 10 if bold else 9)
        c.drawRightString(160 * mm, y - 4 * mm, label)
        c.drawRightString(w - 22 * mm, y - 4 * mm, _money(val))
        y -= 6 * mm
    return y - 6 * mm


def render_invoice_pdf(s: Session, inv: Invoice) -> str:
    path = os.path.join(_files_dir(), f"{inv.number}.pdf")
    c = canvas.Canvas(path, pagesize=A4)
    y = _header(c, "TAX INVOICE", inv.number, inv.issued_at)
    y = _party(c, y, inv, s)
    y = _lines(c, y, inv, s)
    c.setFont("Helvetica", 9)
    c.drawString(20 * mm, y, f"Due {inv.due_at.strftime('%d %b %Y') if inv.due_at else 'on receipt'}. Pay by card in store, or bank transfer quoting {inv.number}.")
    c.drawString(20 * mm, y - 5 * mm, "Thank you for choosing a local independent workshop.")
    c.setFont("Helvetica-Oblique", 7)
    c.drawString(20 * mm, 12 * mm, "Generated by GarageDesk · NVIDIA Nemotron on Nebius Token Factory")
    c.save()
    return path


def render_receipt_pdf(s: Session, inv: Invoice) -> str:
    path = os.path.join(_files_dir(), f"{inv.number}-receipt.pdf")
    c = canvas.Canvas(path, pagesize=A4)
    y = _header(c, "RECEIPT", f"for {inv.number}", datetime.utcnow())
    y = _party(c, y, inv, s)
    pays = s.exec(select(Payment).where(Payment.invoice_id == inv.id)).all()
    c.setFont("Helvetica-Bold", 10)
    c.drawString(20 * mm, y, "Payments received")
    y -= 7 * mm
    c.setFont("Helvetica", 9)
    for p in pays:
        c.drawString(22 * mm, y, f"{p.paid_at.strftime('%d %b %Y %H:%M')}  {p.method}  {p.reference or ''}")
        c.drawRightString(A4[0] - 22 * mm, y, _money(p.amount_cents))
        y -= 6 * mm
    c.setFont("Helvetica-Bold", 11)
    c.drawString(20 * mm, y - 4 * mm, f"Paid in full: {_money(inv.total_cents)} (includes GST {_money(inv.gst_cents)})")
    c.setFont("Helvetica-Oblique", 7)
    c.drawString(20 * mm, 12 * mm, "Generated by GarageDesk · NVIDIA Nemotron on Nebius Token Factory")
    c.save()
    return path
